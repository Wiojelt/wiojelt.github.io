  const originals = new WeakMap();
  function translate(value) {
    const trimmed = value.trim();
    let result = english[trimmed];
    if (!result) {
      let match = trimmed.match(/^(.+) içeriğini (gör|kapat)$/);
      if (match) result = `${match[2] === 'gör' ? 'View' : 'Close'} ${match[1]} details`;
      match = trimmed.match(/^(.+) deposunu CloudStream'de aç$/);
      if (match) result = `Open ${match[1]} in CloudStream`;
      match = trimmed.match(/^(.+) kopyala$/);
      if (match) result = `Copy ${english[match[1]] || match[1]}`;
    }
    if (result?.startsWith(',') || result === '.') return result;
    return result ? value.replace(trimmed, result) : value;
  }
  function update(target, key, read, write) {
    let entries = originals.get(target);
    if (!entries) { entries = {}; originals.set(target, entries); }
    const current = read();
    if (!entries[key] || current !== entries[key].output) entries[key] = {input:current};
    const entry = entries[key];
    entry.output = language === 'en' ? translate(entry.input) : entry.input;
    if (current !== entry.output) write(entry.output);
  }
  function apply(scope = document.body) {
    const walker = document.createTreeWalker(scope, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      if (node.parentElement?.closest('script,style,[data-language]')) continue;
      const text = node;
      update(text, 'text', () => text.nodeValue, value => { text.nodeValue = value; });
    }
    [scope, ...scope.querySelectorAll('*')].forEach(element => {
      for (const attr of ['aria-label','title','alt']) {
        if (element.hasAttribute?.(attr)) update(element, attr, () => element.getAttribute(attr), value => element.setAttribute(attr,value));
      }
    });
  }
  function select(next) {
    language = next;
    document.documentElement.lang = next;
    document.querySelectorAll('[data-language]').forEach(button => button.setAttribute('aria-pressed', String(button.dataset.language === next)));
    apply();
    update(document.querySelector('title'), 'title', () => document.title, value => { document.title = value; });
    document.querySelector('meta[name="description"]').content = next === 'en' ? 'Apps and installation links for CloudStream, BitChord, Nuvio and WioTV.' : 'CloudStream, BitChord, Nuvio ve WioTV için uygulamalar ve kurulum bağlantıları.';
    try { localStorage.setItem('wiostream-language',next); } catch (_) {}
  }
  window.WIO_I18N = {apply, init() {
    document.querySelectorAll('[data-language]').forEach(button => button.addEventListener('click', () => select(button.dataset.language)));
    select(language);
  }};
